#!/usr/bin/env python3
"""Generate 4-bit anti-aliased brand fonts + jackal icons for the CYD Beat Console.

Usage: mkfonts_console.py <fontsource dir> <out fonts.h>
Fonts come from the npm fontsource packages (all SIL OFL 1.1):
  @fontsource/orbitron, @fontsource/share-tech-mono, @fontsource/noto-sans-egyptian-hieroglyphs
(`npm pack` each one and untar it into <fontsource dir>).
"""
import glob, sys
from PIL import Image, ImageDraw, ImageFont

FD = sys.argv[1]
def find(pat):
    hits = glob.glob(f"{FD}/**/{pat}", recursive=True)
    if not hits: sys.exit(f"missing {pat}")
    return hits[0]

ORB = find("orbitron-latin-900-normal.woff")
STM = find("share-tech-mono-latin-400-normal.woff")
HIE = find("noto-sans-egyptian-hieroglyphs-egyptian-hieroglyphs-400-normal.woff")

def pack4(img):
    w, h = img.size
    px = img.load()
    out = bytearray()
    for y in range(h):
        for x in range(0, w, 2):
            a = px[x, y] >> 4
            b = (px[x + 1, y] >> 4) if x + 1 < w else 0
            out.append((a << 4) | b)
    return out

def font(name, path, px, chars):
    f = ImageFont.truetype(path, px)
    asc, desc = f.getmetrics()
    first, last = min(chars), max(chars)
    glyphs, bmp = [], bytearray()
    for cp in range(first, last + 1):
        ch = chr(cp)
        adv = round(f.getlength(ch))
        if cp not in chars:
            glyphs.append((len(bmp), 0, 0, 0, 0, 0)); continue
        l, t, r, b = f.getbbox(ch, anchor="ls")
        w, h = r - l, b - t
        if w <= 0 or h <= 0:
            glyphs.append((len(bmp), 0, 0, 0, 0, adv)); continue
        img = Image.new("L", (w, h), 0)
        ImageDraw.Draw(img).text((-l, -t), ch, font=f, fill=255, anchor="ls")
        glyphs.append((len(bmp), w, h, l, t, adv))      # t = top relative to baseline (negative)
        bmp += pack4(img)
    s = [carr(f"{name}_BMP", bmp),
         f"static const Glyph {name}_G[] = {{\n  " +
         ",\n  ".join(f"{{{o}, {w}, {h}, {xo}, {yo}, {a}}}" for o, w, h, xo, yo, a in glyphs) + "\n};",
         f"static const Font {name} = {{{name}_BMP, {name}_G, {first}, {last}, {asc}, {desc}}};\n"]
    return "\n".join(s)

def icon(name, px):
    f = ImageFont.truetype(HIE, px)
    l, t, r, b = f.getbbox(chr(0x130E3))
    img = Image.new("L", (r - l, b - t), 0)
    ImageDraw.Draw(img).text((-l, -t), chr(0x130E3), font=f, fill=255)
    w, h = img.size
    return (f"#define {name}_W {w}\n#define {name}_H {h}\n" + carr(name, pack4(img))), img

def carr(name, data):
    rows = [", ".join(f"0x{x:02X}" for x in data[i:i + 24]) for i in range(0, len(data), 24)]
    return f"static const uint8_t {name}[] PROGMEM = {{\n  " + ",\n  ".join(rows) + "\n};"

ascii_ = set(range(0x20, 0x7F))
out = ["// Generated by tools/mkfonts_console.py. Orbitron Black, Share Tech Mono,",
       "// Noto Sans Egyptian Hieroglyphs (all SIL OFL 1.1). 4-bit alpha, rows packed 2 px/byte.",
       "#pragma once", "#include <stdint.h>",
       "#ifndef PROGMEM", "#define PROGMEM", "#endif",
       "struct Glyph { uint32_t off; uint8_t w, h; int8_t xo, yo; uint8_t adv; };",
       "struct Font { const uint8_t* bmp; const Glyph* g; uint8_t first, last; uint8_t asc, desc; };", ""]
out.append(font("ORB_BIG", ORB, 92, set(map(ord, "0123456789.-"))))
out.append(font("ORB_20", ORB, 20, ascii_))
out.append(font("ORB_14", ORB, 14, ascii_))
out.append(font("STM_12", STM, 12, ascii_))
out.append(font("STM_16", STM, 16, ascii_))
for name, px in [("JACKAL_S", 18), ("JACKAL_L", 70)]:
    s, img = icon(name, px)
    out.append(s)
open(sys.argv[2], "w").write("\n".join(out) + "\n")
print("wrote", sys.argv[2])
