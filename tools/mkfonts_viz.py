#!/usr/bin/env python3
"""Generate the anti-aliased VLW fonts for the Beat Visualizer (M5GFX loads VLW straight from flash).

Usage: mkfonts_viz.py <fonts dir> <out fonts_viz.h>
<fonts dir> holds the npm fontsource packages (SIL OFL 1.1), unpacked:
  @fontsource/orbitron, @fontsource/share-tech-mono
and NotoSansEgyptianHieroglyphs-Regular.ttf (SIL OFL 1.1) for the jackal, which is stored at U+E000
(VLW only holds 16-bit code points).
"""
import glob
import struct
import sys
from PIL import Image, ImageDraw, ImageFont

FD, OUT = sys.argv[1], sys.argv[2]


def find(pat):
    hits = glob.glob(f"{FD}/**/{pat}", recursive=True) + glob.glob(f"/usr/share/fonts/**/{pat}", recursive=True)
    if not hits:
        sys.exit(f"missing {pat}")
    return hits[0]


ORB9 = find("orbitron-latin-900-normal.woff")
ORB7 = find("orbitron-latin-700-normal.woff")
STM = find("share-tech-mono-latin-400-normal.woff")
HIE = find("NotoSansEgyptianHieroglyphs-Regular.ttf")
JACKAL = "\U000130E3"
ASCII = "".join(chr(c) for c in range(32, 127))


def glyph(font, ch):
    x0, y0, x1, y1 = font.getbbox(ch, anchor="ls")
    adv = round(font.getlength(ch))
    w, h = max(0, x1 - x0), max(0, y1 - y0)
    img = Image.new("L", (max(1, w), max(1, h)), 0)
    if w and h:
        ImageDraw.Draw(img).text((-x0, -y0), ch, font=font, fill=255, anchor="ls")
    return w, h, adv, -y0, x0, img.tobytes() if w and h else b""


# Hieroglyphs for the RAIN visual, stored from U+E001 up (VLW only holds 16-bit code points), and the ankh for
# PYRAMID at U+E000 of its own font.
RAIN_GLYPHS = [0x13000, 0x1300B, 0x13021, 0x1302F, 0x13050, 0x13075, 0x13080, 0x13093, 0x130A7, 0x130B8, 0x130C0,
               0x130D1, 0x130E3, 0x130ED, 0x13153, 0x13171, 0x1317E, 0x1318B, 0x131CB, 0x131F3, 0x13216, 0x13283,
               0x132AA, 0x132F9]
ANKH = 0x132F9


def vlw(path, px, chars, jackal_px=0, remap=None):
    f = ImageFont.truetype(path, px)
    asc, desc = f.getmetrics()
    items = []
    for ch in sorted(set(chars)):
        items.append((ord(ch),) + glyph(f, ch))
    for cp_to, cp_from in (remap or {}).items():
        items.append((cp_to,) + glyph(f, chr(cp_from)))
    if jackal_px:
        hf = ImageFont.truetype(HIE, jackal_px)
        w, h, adv, dy, dx, bm = glyph(hf, JACKAL)
        items.append((0xE000, w, h, adv, dy, dx, bm))
    for it in items:
        assert it[1] < 256 and it[3] < 256, f"glyph {it[0]:x} too wide for VLW ({it[1]} / {it[3]})"
    out = struct.pack(">6i", len(items), 11, px, 0, asc, desc)
    for cp, w, h, adv, dy, dx, _ in items:
        out += struct.pack(">7i", cp, h, w, adv, dy, dx, 0)
    for it in items:
        out += it[6]
    return out


FONTS = [
    ("F_BIG", ORB9, 72, "0123456789-", 0),           # BPM mode number
    ("F_DEC", ORB9, 30, "0123456789.-", 0),          # its decimal
    ("F_LBL", ORB9, 14, ASCII, 0),                   # mode names, labels
    ("F_RAIN", HIE, 17, "", 0, {0xE001 + i: c for i, c in enumerate(RAIN_GLYPHS)}),   # RAIN glyphs
    ("F_ANKH", HIE, 64, "", 0, {0xE000: ANKH}),   # PYRAMID ankh
]

with open(OUT, "w") as o:
    o.write("// Generated by tools/mkfonts_viz.py. Orbitron, Share Tech Mono, Noto Sans Egyptian Hieroglyphs: SIL OFL 1.1.\n")
    o.write("#pragma once\n#include <stdint.h>\n\n")
    total = 0
    for name, path, px, chars, jk, *rm in FONTS:
        data = vlw(path, px, chars, jk, rm[0] if rm else None)
        total += len(data)
        o.write(f"static const uint8_t {name}[{len(data)}] = {{\n")
        for i in range(0, len(data), 24):
            o.write("  " + ",".join(str(b) for b in data[i:i + 24]) + ",\n")
        o.write("};\n\n")
    print(f"{OUT}: {total // 1024} KB")
